using DrWatson
@quickactivate :DRL_RDE
using Accessors
using Statistics
using DataFrames
using Dates
using CairoMakie
CairoMakie.activate!()
##
init_shock_count = 3
target_shock_count = 2

best_configs = get_best_configs_per_target()
row = get_best_config_for_target(best_configs, target_shock_count)
target_shocks = row[:target_shocks]
intermediate_u_p = row[:intermediate_u_p]
intermediate_duration = row[:intermediate_duration]

u_p_start = RDE.SHOCK_PRESSURES[init_shock_count]
u_p_end = RDE.SHOCK_PRESSURES[target_shock_count]
transition_start = 50.0f0
params = RDEParam(tmax = 380.0f0)
env = RDEEnv(
    params, dt = 0.5f0, τ_smooth = 0.1f0,
    observation_strat = StateObservation(),
    reset_strategy = ShiftReset(NShock(init_shock_count)),
    reward_strat = StabilityReward(1.0f0),
    action_strat = DirectScalarPressureAction(),
    context_strat = FixedTargetShockCountStrategy(target_shocks)
)
## Load data (generated by scripts/two_step_example_data.jl)
data = load(datadir("two-step-example-data.jld2"), "data")
##
u_ax_kwargs = (
    yticks = ([0, π / 2, π, 3π / 2, 2π], [L"0", L"\pi/2", L"\pi", L"3\pi/2", L"2\pi"]),
    limits = (nothing, (0.0f0, 2.0f0 * π)), ylabel = L"x - \psi(t) \,\mathrm{mod}\, 2\pi",
)
dpi = 300
u_hm_kwargs = (; rasterize = ceil(Int, dpi * pt / inch))
fig = with_theme(theme_drl_rde()) do
    fig = plot_shifted_history(
        data, env.prob.x;
        use_rewards = false,
        plot_shocks = false,
        u_ax_kwargs,
        fig_kwargs = (;
            size = (16cm, 9cm),
            figure_padding = (16, 16, 16, 32),
        ),
        u_hm_kwargs,
    )
    rowsize!(content(fig[1, 1]), 2, Relative(0.3))
    rowgap!(content(fig[1, 1]), 30)
    hidexdecorations!(fig.content[1], ticks = false)
    proj(x, y) = Makie.shift_project(fig.content[1].scene, Point2(x, y))
    top_heigth = 2π
    stable_start = 0
    stable_end = 50
    bracket!(
        fig.scene, proj(stable_start, top_heigth), proj(stable_end, top_heigth),
        text = "Three stable waves"
    )
    destable_start = 50
    destable_end = 130
    bottom_heigth = -0.0
    bracket!(
        fig.scene, proj(destable_start, bottom_heigth), proj(destable_end, bottom_heigth),
        text = "Destabilization", orientation = :down, align = (:center, :center)
    )
    transition_start = 130
    transition_end = 160
    bracket!(
        fig.scene, proj(transition_start, top_heigth), proj(transition_end, top_heigth),
        text = "Transition to two waves"
    )
    gallop_start = transition_end
    gallop_end = 220
    bracket!(
        fig.scene, proj(gallop_start, bottom_heigth), proj(gallop_end, bottom_heigth),
        text = "Two galloping waves", orientation = :down, align = (:center, :center)
    )
    stabilization_start = 230
    stabilization_end = 330
    bracket!(
        fig.scene, proj(stabilization_start, top_heigth), proj(stabilization_end, top_heigth),
        text = "Stabilization of galloping waves", align = (:left, :center)
    )
    two_wave_start = 330
    two_wave_end = 380
    bracket!(
        fig.scene, proj(two_wave_start, bottom_heigth), proj(two_wave_end, bottom_heigth),
        text = "Two stable waves", orientation = :down, align = (:center, :center)
    )
    fig
end
##
foreach([".png", ".pdf"]) do ext
    wsave(plotsdir("figures", "two-step-example" * ext), fig)
end
